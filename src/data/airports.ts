// Helper functions
export function getAirportByIata(iata: string): Airport | undefined {
  return AIRPORT_DATABASE.find(airport => airport.iata === iata);
}

export function getAirportsByCountry(country: string): Airport[] {
  return AIRPORT_DATABASE.filter(airport => airport.country === country);
}

export function getAirportsByContinent(continent: string): Airport[] {
  return AIRPORT_DATABASE.filter(airport => airport.continent === continent);
}

export function getAirportsBySize(size: string): Airport[] {
  return AIRPORT_DATABASE.filter(airport => airport.size === size);
}

export function searchAirports(query: string): Airport[] {
  const lowerQuery = query.toLowerCase();
  return AIRPORT_DATABASE.filter(airport =>
    airport.iata.toLowerCase().includes(lowerQuery) ||
    airport.name.toLowerCase().includes(lowerQuery) ||
    airport.city.toLowerCase().includes(lowerQuery) ||
    airport.country.toLowerCase().includes(lowerQuery)
  );
}

// Calculate distance between two airports (great circle distance in nautical miles)
export function calculateDistance(airport1: Airport, airport2: Airport): number {
  const R = 3440.06; // Earth's radius in nautical miles
  const dLat = toRadians(airport2.latitude - airport1.latitude);
  const dLon = toRadians(airport2.longitude - airport1.longitude);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRadians(airport1.latitude)) *
      Math.cos(toRadians(airport2.latitude)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c);
}

function toRadians(degrees: number): number {
  return (degrees * Math.PI) / 180;
}
